/* =========================================
   CONFETTI
========================================= */

function createConfetti() {

    const container =
        document.getElementById(
            "confetti"
        );


    container.innerHTML = "";


    for (
        let i = 0;
        i < 70;
        i++
    ) {

        const piece =
            document.createElement(
                "div"
            );


        piece.className =
            "confetti";


        piece.style.left =
            Math.random() * 100 + "vw";


        piece.style.background =
            i % 2 === 0
                ? "#ff4164"
                : "#a66cff";


        piece.style.animationDelay =
            Math.random() * 1 + "s";


        container.appendChild(
            piece
        );

    }


    setTimeout(function() {

        container.innerHTML = "";

    }, 3000);

}
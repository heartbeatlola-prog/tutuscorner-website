/* =========================================
   START GAME
========================================= */

startBtn.addEventListener("click", function() {

    currentQuestion = 0;

    score = 0;

    lives = 3;

    startScreen.classList.remove("active");

    gameScreen.classList.add("active");

    showQuestion();

});


/* =========================================
   SHOW QUESTION
========================================= */

function showQuestion() {

    const current =
        questions[currentQuestion];


    roundName.textContent =
        current.round;


    difficulty.textContent =
        current.difficulty;


    questionNumber.textContent =
        `${currentQuestion + 1} / ${questions.length}`;


    question.textContent =
        current.question;


    questionHint.textContent =
        current.hint;


    /* PROGRESS */

    const percentage =
        (currentQuestion / questions.length) * 100;


    progressBar.style.width =
        percentage + "%";


    /* LIVES */

    updateLives();


    /* CLEAR */

    answers.innerHTML = "";

    feedback.textContent = "";

    nextBtn.style.display = "none";


    /* CREATE ANSWERS */

    current.answers.forEach(function(answer, index) {

        const button =
            document.createElement("button");


        button.className =
            "answer";


        button.textContent =
            answer;


        button.addEventListener(
            "click",
            function() {

                chooseAnswer(
                    index,
                    button
                );

            }
        );


        answers.appendChild(button);

    });

}


/* =========================================
   CHOOSE ANSWER
========================================= */

function chooseAnswer(
    selectedIndex,
    selectedButton
) {

    const current =
        questions[currentQuestion];


    /* PREVENT DOUBLE CLICK */

    const allButtons =
        document.querySelectorAll(".answer");


    allButtons.forEach(function(button) {

        button.disabled = true;

    });


    /* CORRECT */

    if (
        selectedIndex ===
        current.correct
    ) {

        score++;

        selectedButton.classList.add(
            "correct"
        );

        feedback.textContent =
            current.correctMessage;

    }

    /* WRONG */

    else {

        lives--;

        selectedButton.classList.add(
            "wrong"
        );


        allButtons[
            current.correct
        ].classList.add(
            "correct"
        );


        feedback.textContent =
            current.wrongMessage;


        updateLives();


        /* GAME OVER */

        if (lives <= 0) {

            feedback.textContent =
                "💀 NO LIVES LEFT. But you can still see your score.";

        }

    }


    nextBtn.style.display =
        "inline-block";

}


/* =========================================
   NEXT QUESTION
========================================= */

nextBtn.addEventListener("click", function() {

    currentQuestion++;


    if (
        currentQuestion >=
        questions.length
    ) {

        finishGame();

    }

    else {

        showQuestion();

    }

});


/* =========================================
   UPDATE LIVES
========================================= */

function updateLives() {

    let hearts = "";


    for (
        let i = 0;
        i < 3;
        i++
    ) {

        if (i < lives) {

            hearts += "❤️ ";

        }

        else {

            hearts += "🖤 ";

        }

    }


    livesDisplay.textContent =
        hearts;

}


/* =========================================
   FINISH GAME
========================================= */

function finishGame() {

    gameScreen.classList.remove(
        "active"
    );

    resultScreen.classList.add(
        "active"
    );


    finalScore.textContent =
        score;


    const percentage =
        (score / questions.length) * 100;


    /* PERFECT */

    if (percentage === 100) {

        resultEmoji.textContent =
            "👑";

        resultTitle.textContent =
            "YOU KNOW US TOO WELL 😭❤️";

        rank.textContent =
            "👑 FAITH KNOWS THE LORE";

        resultMessage.textContent =
            "15/15?! Nahhh. You remembered everything. After 6 years, you clearly know the story ❤️";

        createConfetti();

    }


    /* 80%+ */

    else if (percentage >= 80) {

        resultEmoji.textContent =
            "🥹";

        resultTitle.textContent =
            "OKAYYYY FAITH ❤️";

        rank.textContent =
            "💜 CERTIFIED LORE KEEPER";

        resultMessage.textContent =
            "You actually know your story. A few memories escaped you, but you did REALLY well.";

    }


    /* 60%+ */

    else if (percentage >= 60) {

        resultEmoji.textContent =
            "👀";

        resultTitle.textContent =
            "NOT BAD AT ALL";

        rank.textContent =
            "❤️ MEMORY KEEPER";

        resultMessage.textContent =
            "You know the story, but Mayor might have to remind you about a few chapters 😂";

    }


    /* 40%+ */

    else if (percentage >= 40) {

        resultEmoji.textContent =
            "😭";

        resultTitle.textContent =
            "WE NEED TO TALK";

        rank.textContent =
            "📝 LORE STUDENT";

        resultMessage.textContent =
            "After all these years?! 😭 Time for a little revision.";

    }


    /* LOW */

    else {

        resultEmoji.textContent =
            "💀";

        resultTitle.textContent =
            "FAITH PLEASE 😭";

        rank.textContent =
            "🚨 LORE UNDER INVESTIGATION";

        resultMessage.textContent =
            "Six years and THIS score?! Mayor's office would like a word 😂";

    }

}


